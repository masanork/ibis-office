// Generate worker/help-content.ts from assets/help/{ja,en}/*.md so Rust and Cloudflare Worker share a single source of truth.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const assetsHelpDir = path.join(repoRoot, 'assets', 'help');
const outFile = path.join(repoRoot, 'worker', 'help-content.ts');

const locales = ['ja', 'en'];
const filesOrder = [
  'index.md',
  'getting-started.md',
  'shortcuts.md',
  'markdown-basics.md',
  'marp-slides.md',
  'workbook-markdown.md',
  'mermaid-diagrams.md',
  'okf-and-vault.md',
  'office-and-lawtext.md',
];

const data = {};
for (const locale of locales) {
  const dir = path.join(assetsHelpDir, locale);
  data[locale] = filesOrder.map((name) => {
    const fullPath = path.join(dir, name);
    const content = fs.readFileSync(fullPath, 'utf8');
    return { path: `help/${name}`, content };
  });
}

const ts = `// SPDX-License-Identifier: AGPL-3.0-only
// AUTO-GENERATED by scripts/sync-help-assets.mjs from assets/help/{ja,en}/*.md. Do not edit manually.

export type HelpLocale = 'ja' | 'en';

export interface HelpFile {
  path: string;
  content: string;
}

export const HELP_FILES: Record<HelpLocale, HelpFile[]> = ${JSON.stringify(data, null, 2)};

export function normalizeHelpLocale(raw?: string | null): HelpLocale {
  if (!raw || !raw.trim()) return 'ja';
  return raw.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}
`;

fs.writeFileSync(outFile, ts, 'utf8');
console.log(`Generated ${path.relative(repoRoot, outFile)} (${locales.length} locales, ${filesOrder.length} files each).`);
