#!/usr/bin/env python3
"""Generate Rust report metadata from rule source at the pinned Harunobu commit."""
import json, subprocess, sys
from pathlib import Path
repo = Path(sys.argv[1]).resolve()
commit = '88014ff9cfe685d4e0e5f24a2d4d2e021ca3fd9f'
if subprocess.check_output(['git', '-C', str(repo), 'rev-parse', 'HEAD'], text=True).strip() != commit:
    raise SystemExit('Harunobu checkout is not at the pinned revision')
code = '''import json
from harunobu.rules.registry import registry
registry.discover()
print(json.dumps([[r.rule_id,r.rule_name,r.description] for r in registry.get_all()],ensure_ascii=False))
'''
data = json.loads(subprocess.check_output([str(repo / '.venv/bin/python'), '-I', '-X', 'utf8', '-c', code], cwd=repo, text=True))
out = Path(__file__).resolve().parent.parent / 'crates/ibis-doc-model/src/machine_readability_rule_metadata_generated.rs'
lines = ['// Generated by scripts/machine-readability-rule-metadata.py from Harunobu 0.2.2.', '// Copyright (c) 2026 Digital Agency of Japan. MIT; see ../HARUNOBU-MIT.txt.', 'pub static RULE_METADATA: &[RuleMetadata] = &[']
for rule_id, name, description in data:
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines.append(f'    RuleMetadata {{ id: {quote(rule_id)}, name: {quote(name)}, description: {quote(description)} }},')
lines.append('];')
out.write_text('\n'.join(lines) + '\n')
